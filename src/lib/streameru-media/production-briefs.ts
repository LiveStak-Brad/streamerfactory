/**
 * Lesson Production Briefs — source of truth for what assets would help each lesson.
 * Code-seeded so the admin setup center works before/without DB rows; DB holds upload status.
 */

import type { AssetPriority, AssetType, OwnershipKind } from "@/lib/streameru-media/types";
import { CURRICULUM } from "@/lib/resources/curriculum";

export type BriefAsset = {
  /** Stable key within lesson — used as placeholder_key / reusable seed id suffix */
  key: string;
  assetType: AssetType;
  title: string;
  description: string;
  purpose: string;
  sectionKey: string;
  placement: string;
  captureInstructions: string;
  highlight?: string;
  cropBlur?: string;
  device?: string;
  orientation?: string;
  dimensionsHint?: string;
  caption: string;
  alt: string;
  priority: AssetPriority;
  required: boolean;
  ownership: OwnershipKind;
  privacyWarning?: string;
  reusableKey?: string;
  /** Diagram: Cursor can generate branded SVG */
  cursorCanGenerate?: boolean;
  founderQuestion?: string;
  videoTalkingPoints?: string[];
  estimatedMinutes?: number;
};

export type LessonProductionBrief = {
  lessonSlug: string;
  lessonTitle: string;
  programName: string;
  globalOrder: number;
  assets: BriefAsset[];
};

function brief(
  slug: string,
  assets: BriefAsset[],
): LessonProductionBrief {
  const lesson = CURRICULUM.find((l) => l.slug === slug);
  return {
    lessonSlug: slug,
    lessonTitle: lesson?.title ?? slug,
    programName: lesson?.programName ?? "StreamerU",
    globalOrder: lesson?.globalOrder ?? 0,
    assets,
  };
}

