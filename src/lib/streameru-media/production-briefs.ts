/** Compact brief builder for remaining curriculum lessons */
function assetsFor(
  items: Array<Omit<BriefAsset, "sectionKey"> & { sectionKey?: string }>,
): BriefAsset[] {
  return items.map((a) => ({
    sectionKey:
      a.sectionKey ??
      (a.assetType === "diagram"
        ? "Diagrams"
        : a.assetType === "founder_story"
          ? "From Brad's Experience"
          : a.assetType === "worksheet" || a.assetType === "checklist"
            ? "Downloads"
            : "Screenshots"),
    ...a,
  }));
}

