export const LESSON_PRODUCTION_BRIEFS: LessonProductionBrief[] = [LESSON_1, ...REST].sort(
  (a, b) => a.globalOrder - b.globalOrder,
);

export function getBriefForLesson(slug: string): LessonProductionBrief | null {
  return LESSON_PRODUCTION_BRIEFS.find((b) => b.lessonSlug === slug) ?? null;
}

export function listAllBriefAssets(): Array<BriefAsset & { lessonSlug: string; lessonTitle: string }> {
  return LESSON_PRODUCTION_BRIEFS.flatMap((b) =>
    b.assets.map((a) => ({ ...a, lessonSlug: b.lessonSlug, lessonTitle: b.lessonTitle })),
  );
}
